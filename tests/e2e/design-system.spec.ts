import { test, expect } from '@playwright/test'
import { placeWidget, savedProject } from './helpers/project'

test('design system tokens, themes, component variants and local libraries preserve project flows', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  const baseline = await savedProject(page)
  await placeWidget(page, '按钮', { x: 120, y: 120 })
  await page.getByRole('button', { name: '设计系统' }).click()
  const panel = page.getByTestId('design-system-panel')

  await panel.getByRole('textbox', { name: '新主题名称' }).fill('Night')
  await panel.getByRole('button', { name: '新增' }).click()
  await expect(panel.locator('select').first()).toHaveValue(/theme/)
  await panel.getByRole('textbox', { name: '令牌名称' }).fill('accent')
  await panel.getByRole('textbox', { name: '令牌值' }).fill('#4169e1')
  await panel.getByRole('button', { name: '添加', exact: true }).click()
  await expect(panel.getByText('accent', { exact: true })).toBeVisible()

  const widgetSurface = page.locator('.widget-content.widget-button').last()
  await page.locator('.design-widget').last().click()
  const defaultColor = await widgetSurface.evaluate(element => getComputedStyle(element).color)
  const colorBinding = panel.locator('.token-binding-row select').first()
  await colorBinding.selectOption({ label: 'Base / accent' })
  await expect(colorBinding).toHaveValue(/\.accent$/)
  await expect.poll(() => widgetSurface.evaluate(element => getComputedStyle(element).color)).not.toBe(defaultColor)
  await expect(widgetSurface.locator('.base-button')).toHaveCSS('color', 'rgb(65, 105, 225)')
  await panel.getByRole('textbox', { name: '组件名称' }).fill('Primary Action')
  await panel.getByTestId('create-component').click()
  const component = panel.locator('.component-library-item').filter({ hasText: 'Primary Action' })
  await expect(component).toBeVisible()
  await component.getByTitle('编辑组件与变体').click()
  const sourceEditor = component.getByRole('textbox', { name: 'Component source JSON' })
  const source = JSON.parse(await sourceEditor.inputValue())
  source.variants = { axes: { size: ['small', 'large'], tone: ['neutral', 'accent'] }, combinations: { compact: { size: 'small', tone: 'neutral' }, primary: { size: 'large', tone: 'accent' } } }
  await sourceEditor.fill(JSON.stringify(source, null, 2))
  await component.getByRole('button', { name: 'Apply source' }).click()
  await component.getByRole('button', { name: '插入实例' }).click()
  const variant = panel.getByLabel('Variant combination')
  await expect(variant).toBeVisible()
  await variant.selectOption('primary')
  await expect(variant).toHaveValue('primary')
  await expect(panel.getByTestId('reset-component-overrides')).toBeVisible()

  page.once('dialog', dialog => dialog.accept('test override'))
  await panel.getByRole('button', { name: '覆盖源属性' }).click()
  await panel.getByTestId('reset-component-overrides').click()

  const libraryDownload = page.waitForEvent('download')
  await panel.getByRole('button', { name: '导出本地库' }).click()
  const libraryPath = await (await libraryDownload).path()
  expect(libraryPath).toBeTruthy()
  page.once('dialog', dialog => dialog.accept())
  await panel.locator('input[type=file]').setInputFiles(libraryPath!)
  await expect(panel.getByRole('status')).toContainText('Imported')
  await panel.getByTestId('detach-component').click()
  await expect(panel.getByTestId('detach-component')).toHaveCount(0)

  const result = await savedProject(page)
  expect(result.designSystem.themes).toHaveProperty('default')
  expect(Object.values(result.designSystem.themes).some((theme: any) => theme.name === 'Night')).toBe(true)
  expect(Object.values(result.designSystem.tokenSets).some((set: any) => set.tokens.accent?.$value === '#4169e1')).toBe(true)
  expect(result.flows).toEqual(baseline.flows)
  expect(errors).toEqual([])
})
