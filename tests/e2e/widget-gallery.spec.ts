import { test, expect } from '@playwright/test'
test('shared widget renderer handles inputs, nested layouts, dialogs, splitter drag, table edits and shortcuts',async({page})=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
  await page.goto('/tests/e2e/widget-harness.html')
  const tabGroups=page.locator('.widget-content.widget-tabs')
  await expect(tabGroups).toHaveCount(2)
  await expect(tabGroups.first().locator('.widget-tabs-header button')).toHaveCount(2)
  await expect(page.getByText('第一页标题')).toBeVisible()
  await page.getByRole('button',{name:'详情'}).click()
  await expect(page.getByText('第二页内容')).toBeVisible()
  await page.getByRole('button',{name:'概览'}).click()
  await expect(page.getByText('子按钮')).toBeVisible()
  await page.locator('.widget-check input').check()
  await page.getByRole('radio',{name:'手动'}).check()
  await expect.poll(()=>page.evaluate(()=>((window as any).__widgetEvents as any[]).filter(item=>item.kind==='input').length)).toBeGreaterThanOrEqual(2)
  const cell=page.locator('.widget-table tbody tr input[type=number]')
  await expect(cell).toHaveValue('23')
  await cell.fill('24');await cell.press('Tab')
  await expect.poll(()=>page.evaluate(()=>((window as any).__widgetEvents as any[]).find(item=>item.value?.rowKey==='r1')?.value?.newValue)).toBe(24)
  await expect(page.locator('.widget-dialog-surface')).toBeVisible()
  const splitterHandle=(await page.locator('.widget-splitter-handle').boundingBox())!;await page.mouse.move(splitterHandle.x+splitterHandle.width/2,splitterHandle.y+splitterHandle.height/2);await page.mouse.down();await page.mouse.move(splitterHandle.x+splitterHandle.width/2+30,splitterHandle.y+splitterHandle.height/2,{steps:4});await page.mouse.up()
  await expect.poll(()=>page.evaluate(()=>((window as any).__widgetEvents as any[]).some(item=>item.value?.ratio))).toBe(true)
  await page.keyboard.press('Control+Alt+J')
  await expect.poll(()=>page.evaluate(()=>((window as any).__widgetEvents as any[]).filter(item=>item.value===undefined&&item.action?.flowId==='shortcut-flow').length)).toBe(1)
  await page.getByRole('button',{name:'工具'}).click()
  const menu=page.getByRole('menu').filter({has:page.getByRole('menuitem',{name:'共享动作'})})
  await expect(menu).toBeVisible()
  await expect(menu.getByRole('menuitem',{name:'隐藏动作'})).toHaveCount(0)
  await expect(page.locator('.widget-toolbar').getByRole('button',{name:'隐藏动作'})).toHaveCount(0)
  await expect(page.locator('.widget-toolbar').locator('svg')).toHaveCount(1)
  await expect(page.locator('.widget-content.widget-list').filter({hasText:'禁用项目'})).toHaveAttribute('inert','')
  const bounds=await menu.boundingBox();expect(bounds).toBeTruthy();expect(bounds!.y+bounds!.height).toBeLessThanOrEqual(980)
  await menu.getByRole('menuitem',{name:'共享动作'}).click()
  await expect.poll(()=>page.evaluate(()=>((window as any).__widgetEvents as any[]).filter(item=>item.action?.flowId==='shortcut-flow').length)).toBe(2)
  await expect.poll(()=>errors).toEqual([])
})
test('project locale translates component text, options and table headers',async({page})=>{
  await page.goto('/tests/e2e/widget-harness.html')
  await page.evaluate(()=>{(window as any).__widgetSetLocale?.('en-US')})
  await expect(page.getByText('First page title')).toBeVisible()
  await expect(page.getByRole('button',{name:'Overview'})).toBeVisible()
  await expect(page.locator('.widget-table th').nth(1)).toHaveText('Name')
  await expect(page.locator('.widget-select select option:not([value=""])').first()).toHaveText('Device A')
})
test('restores unbound session input and keeps a value binding above stale input snapshots',async({page})=>{
  await page.goto('/tests/e2e/widget-harness.html')
  const inputs=page.locator('.widget-input input')
  await expect(inputs).toHaveCount(2)
  await expect(inputs.nth(0)).toHaveValue('会话输入')
  await expect(inputs.nth(1)).toHaveValue('绑定值')
  const restoredTab=page.locator('.widget-content.widget-tabs').filter({has:page.getByRole('button',{name:'恢复选项卡'})}).getByRole('button',{name:'恢复选项卡'})
  await expect(restoredTab).toHaveClass(/active/)
})
