test('backend snapshots replace stale input values and device context changes discard pending file selections',async({page})=>{
  await page.goto('/tests/e2e/device-widgets-harness.html')
  await page.evaluate(()=>{
    const project=(window as any).__deviceProject,snapshot=(window as any).__deviceSnapshot
    const input=project.pages[0].widgets.find((widget:any)=>widget.kind==='input')
    input.props.format='text';input.bindings.value={source:'backend',key:'host',path:'devices.$deviceKey.label'}
    snapshot.context.windowInstanceId='device-1';snapshot.inputs[input.id]='stale local input'
  })
  const input=page.locator('.widget-input input')
  await expect(input).toHaveValue('Bound device')
  await page.evaluate(()=>(window as any).__deviceSnapshot.backends.host.devices['usb.device.1'].label='Updated by backend')
  await expect(input).toHaveValue('Updated by backend')
  await input.fill('Uncommitted input')
  await page.evaluate(()=>(window as any).__deviceFileMode='deferred')
  await page.locator('.widget-file-picker').getByRole('button',{name:'浏览…'}).click()
  await expect(page.locator('.widget-file-picker [aria-busy=true]')).toHaveCount(1)
  await page.evaluate(()=>{
    const snapshot=(window as any).__deviceSnapshot
    snapshot.backends.host.devices['usb.device.2']={label:'Updated by backend'}
    snapshot.context={windowInstanceId:'device-2',deviceKey:'usb.device.2'}
    snapshot.inputs={}
  })
  await expect(input).toHaveValue('Updated by backend')
  await page.evaluate(()=>(window as any).__deviceResolveFile())
  await expect(page.locator('.widget-file-picker').getByRole('textbox')).toHaveValue('')
  expect(await page.evaluate(()=>(window as any).__deviceEvents.some((event:any)=>event.action?.flowId==='file'))).toBe(false)
})
