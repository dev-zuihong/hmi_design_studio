test('compact controls keep their value and button text inside the canvas and numeric dropdowns preserve types',async({page})=>{
  await page.goto('/tests/e2e/device-widgets-harness.html')
  await expect(page.getByText('未知控件：scroll',{exact:false})).toHaveCount(0)
  await expect(page.getByText('Scrollable content',{exact:true})).toBeVisible()
  const metric=page.locator('.widget-number .metric-value')
  await expect(metric).toContainText('3')
  const fits=await metric.evaluate(element=>{const outer=element.closest('.widget-content')!.getBoundingClientRect();const range=document.createRange();range.selectNodeContents(element);const inner=range.getBoundingClientRect();return inner.top>=outer.top&&inner.bottom<=outer.bottom&&inner.right<=outer.right})
  expect(fits).toBe(true)
  const button=page.locator('.widget-button .base-button')
  await expect(button).toContainText('导出')
  expect(await button.evaluate(element=>{const outer=element.getBoundingClientRect();const node=[...element.childNodes].find(node=>node.nodeType===Node.TEXT_NODE&&node.textContent?.includes('导出'))!;const range=document.createRange();range.selectNode(node);const inner=range.getBoundingClientRect();return inner.left>=outer.left&&inner.right<=outer.right&&inner.bottom<=outer.bottom})).toBe(true)
  const select=page.locator('.widget-select select')
  await expect(select.locator('option:checked')).toHaveText('Option B')
  await select.selectOption('1')
  await expect(select.locator('option:checked')).toHaveText('Option A')
  await expect.poll(()=>page.evaluate(()=>(window as any).__deviceEvents.find((event:any)=>event.action?.flowId==='numericSelect')?.value)).toBe(1)
  const address=page.locator('[data-row-key="usb.a"] .validated-input input')
  await address.fill('0207F000');await address.press('Tab')
  await expect(page.locator('[data-row-key="usb.a"] .validated-input [role=status]')).toBeVisible()
  expect(await page.evaluate(()=>(window as any).__deviceEvents.some((event:any)=>event.action?.flowId==='cellEdit'&&event.value?.columnKey==='address'))).toBe(false)
  await address.fill('4294967295');await address.press('Tab')
  await expect.poll(()=>page.evaluate(()=>(window as any).__deviceEvents.find((event:any)=>event.action?.flowId==='cellEdit'&&event.value?.columnKey==='address')?.value.newValue)).toBe('4294967295')
})

